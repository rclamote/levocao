  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  const attributes = ['placeholder', 'aria-label', 'title'];
  const isEnglish = () => /^\/en(?:\/|$)/.test(window.location.pathname);
  const longerPhrases = Object.keys(translations).filter((key) => key.length >= 20).sort((a, b) => b.length - a.length);
  const translateValue = (value) => {
    const trimmed = value.trim();
    if (Object.prototype.hasOwnProperty.call(translations, trimmed)) {
      return value.replace(trimmed, translations[trimmed]);
    }
    // Some existing UI elements combine two phrases in the same text node.
    let next = value;
    for (const phrase of longerPhrases) {
      if (next.includes(phrase)) next = next.split(phrase).join(translations[phrase]);
    }
    return next;
  };

  function applyTranslations(root = document.body) {
    const english = isEnglish();
    if (!root) return;

    const walk = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walk.nextNode()) textNodes.push(walk.currentNode);

    for (const node of textNodes) {
      if (['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA'].includes(node.parentElement?.tagName)) continue;
      if (!originalText.has(node)) originalText.set(node, node.textContent);
      const source = originalText.get(node);
      const next = english ? translateValue(source) : source;
      if (node.textContent !== next) node.textContent = next;
    }

    const elements = [root, ...(root.querySelectorAll?.('*') || [])];
    for (const element of elements) {
      if (!element.getAttribute) continue;
      if (!originalAttributes.has(element)) originalAttributes.set(element, {});
      const sources = originalAttributes.get(element);
      for (const attribute of attributes) {
        if (!element.hasAttribute(attribute)) continue;
        if (!Object.prototype.hasOwnProperty.call(sources, attribute)) {
          sources[attribute] = element.getAttribute(attribute);
        }
        const value = english ? translateValue(sources[attribute]) : sources[attribute];
        if (element.getAttribute(attribute) !== value) element.setAttribute(attribute, value);
      }
    }
    document.documentElement.lang = english ? 'en' : 'pt';
    if (english) {
      document.title = 'Levo o Cão | Dog-friendly places in Portugal';
      document.querySelector('meta[name="description"]')?.setAttribute('content',
        'Discover dog-friendly beaches, restaurants, accommodation and walks in Portugal. Real tips from a community of dog owners.');
    }
  }

  function currentUrlInLanguage(toEnglish) {
    const path = window.location.pathname;
    const base = path.replace(/^\/en(?=\/|$)/, '') || '/';
    return toEnglish ? '/en' + (base === '/' ? '/' : base) : base;
  }

  function insertSwitcher() {
    const nav = document.querySelector('#app nav');
    const target = nav?.querySelector('.flex.items-center.gap-2');
    if (!target || document.getElementById('language-switcher')) return;
    const switcher = document.createElement('button');
    switcher.type = 'button';
    switcher.id = 'language-switcher';
    switcher.className = 'px-2 py-1.5 rounded-full border border-sand text-xs font-semibold text-sage hover:bg-sand transition';
    switcher.textContent = isEnglish() ? '🇬🇧 EN ▾' : '🇵🇹 PT ▾';
    switcher.setAttribute('aria-label', isEnglish() ? 'Switch to Portuguese' : 'Switch to English');
    switcher.title = isEnglish() ? 'Mudar para português' : 'Switch to English';
    switcher.addEventListener('click', () => {
      window.location.assign(currentUrlInLanguage(!isEnglish()));
    });
    target.insertBefore(switcher, target.firstChild);
  }

  document.addEventListener('DOMContentLoaded', () => {
    insertSwitcher();
    applyTranslations();
    let pending = false;
    const observer = new MutationObserver(() => {
      if (pending) return;
      pending = true;
      requestAnimationFrame(() => {
        pending = false;
        applyTranslations();
      });
    });
    observer.observe(document.body, { childList: true, subtree: true });
  });
